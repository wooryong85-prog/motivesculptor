-- The trigger keeps trainer assignment and total completed sessions consistent even
-- when concurrent requests are submitted from different browsers.
create or replace function public.validate_completed_session() returns trigger
language plpgsql security definer set search_path = ''
as $$
declare booked public.member_enrollments%rowtype; used integer; share numeric;
begin
 select * into booked from public.member_enrollments where id=new.enrollment_id for update;
 if not found or booked.trainer_id is distinct from new.trainer_id then
   raise exception '수업의 담당 트레이너가 등록 내역과 다릅니다';
 end if;
 if booked.payment_method is null then raise exception '기존 등록의 결제 방식을 먼저 지정하세요'; end if;
 select coalesce(sum(quantity),0) into used from public.completed_sessions where enrollment_id=new.enrollment_id;
 if used+new.quantity>booked.session_count then raise exception '등록 수업 수를 초과합니다'; end if;
 select share_rate into share from public.trainers where id=new.trainer_id;
 new.payout_amount=round(
   (booked.price / case when booked.payment_method='card' then 1.1 else 1 end)
   / booked.session_count * new.quantity * share, 2);
 return new;
end $$;
drop trigger if exists completed_session_validate on public.completed_sessions;
create trigger completed_session_validate before insert on public.completed_sessions
for each row execute function public.validate_completed_session();

