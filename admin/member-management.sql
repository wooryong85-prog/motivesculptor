-- Run once in Supabase Dashboard > SQL Editor as the project owner.
create table if not exists public.member_enrollments (
 id bigint generated by default as identity primary key,
 member_name text not null check (char_length(trim(member_name)) between 1 and 80),
 trainer_name text not null check (char_length(trim(trainer_name)) between 1 and 80),
 registered_at date not null, session_count integer not null check (session_count>0),
 price numeric(12,0) not null check (price>=0), is_renewal boolean not null default false,
 created_at timestamptz not null default now());
alter table public.member_enrollments enable row level security;
create policy "authenticated admins read enrollments" on public.member_enrollments for select to authenticated using (true);
create policy "authenticated admins add enrollments" on public.member_enrollments for insert to authenticated with check (true);
create policy "authenticated admins update enrollments" on public.member_enrollments for update to authenticated using (true) with check (true);
create index if not exists member_enrollments_registered_at_idx on public.member_enrollments(registered_at desc);
create index if not exists member_enrollments_trainer_date_idx on public.member_enrollments(trainer_name,registered_at desc);

